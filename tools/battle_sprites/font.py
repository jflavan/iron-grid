UMLAUT_BASE = {"Ä": "A", "Ö": "O", "Ü": "U"}
CHARS = "".join(GLYPHS.keys()) + "".join(UMLAUT_BASE.keys())


def write_font(out):
    os.makedirs(os.path.join(out, "font"), exist_ok=True)
    white, clear = (255, 255, 255, 255), (0, 0, 0, 0)
    rows = [[clear] * (6 * len(CHARS)) for _ in range(8)]
    for i, ch in enumerate(CHARS):
        glyph = GLYPHS[UMLAUT_BASE.get(ch, ch)].split()
        for y, line in enumerate(glyph):
            for x, c in enumerate(line):
                if c == "#":
                    rows[y + 1][i * 6 + x] = white
        if ch in UMLAUT_BASE:
            rows[0][i * 6 + 1] = white
            rows[0][i * 6 + 3] = white
    png.write_png(os.path.join(out, "font", "font5x7.png"), 6 * len(CHARS), 8, rows)
    with open(os.path.join(out, "font", "font5x7.json"), "w", encoding="utf-8") as f:
        json.dump({"advance": 6, "height": 8, "chars": CHARS}, f, ensure_ascii=False)
        f.write("\n")
